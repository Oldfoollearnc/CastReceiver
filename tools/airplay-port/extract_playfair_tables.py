#!/usr/bin/env python3
"""Generate C# constant tables from the UxPlay FairPlay reference sources.

Extracted (never hand-transcribed -- a single wrong byte yields a receiver that
silently never connects):

  1. lib/playfair/omg_hax.h + lib/playfair/omg_hax.c -> FairPlayTables.g.cs
     The reverse-engineered PlayFair ("omg_hax") S-box / T-table / message
     tables, plus the inline constants (default_sap, sap_key_material,
     index_mangle, initial_session_key, static_source_1/2).

  2. lib/fairplay_playfair.c -> FairPlayConstants.g.cs
     The four 142-byte fp-setup replies and the 12-byte fp-setup type-1 header.

Usage:
    python extract_playfair_tables.py <omg_hax.h> <omg_hax.c> <FairPlayTables.g.cs> \
                                      <fairplay_playfair.c> <FairPlayConstants.g.cs>
"""
import re
import sys
from pathlib import Path

TABLE_NAMES = {
    "message_key": "MessageKey",
    "message_iv": "MessageIv",
    "z_key": "ZKey",
    "x_key": "XKey",
    "t_key": "TKey",
    "default_sap": "DefaultSap",
    "sap_iv": "SapIv",
    "sap_key_material": "SapKeyMaterial",
    "index_mangle": "IndexMangle",
    "initial_session_key": "InitialSessionKey",
    "static_source_1": "StaticSource1",
    "static_source_2": "StaticSource2",
}
for _i in range(1, 11):
    TABLE_NAMES["table_s%d" % _i] = "TableS%d" % _i

CONST_NAMES = {
    "reply_message": "ReplyMessage",
    "fp_header": "FpHeader",
}

TYPE_MAP = {
    "unsigned char": "byte[]",
    "char": "byte[]",
    "const unsigned char": "byte[]",
    "unsigned long": "uint[]",
    "uint32_t": "uint[]",
    "unsigned int": "uint[]",
}

DECL = re.compile(
    r"\b(unsigned\s+char|unsigned\s+long|uint32_t|unsigned\s+int|const\s+unsigned\s+char|char)\s+"
    r"([A-Za-z_]\w*)\s*"
    r"((?:\[[^\]]*\])+)\s*=\s*\{(.*?)\};",
    re.S,
)
HEX = re.compile(r"0[xX][0-9a-fA-F]+")


def parse(paths):
    out = []
    for path in paths:
        text = Path(path).read_text(encoding="utf-8", errors="replace")
        text = re.sub(r"/\*.*?\*/", "", text, flags=re.S)
        text = re.sub(r"//[^\n]*", "", text)
        for m in DECL.finditer(text):
            ctype = " ".join(m.group(1).split())
            out.append((ctype, m.group(2), m.group(3),
                        [int(t, 16) for t in HEX.findall(m.group(4))]))
    return out


def emit_byte_array(cs_name, values):
    hexstr = "".join("%02x" % (v & 0xFF) for v in values)
    lines = ['        "%s"' % hexstr[i:i + 128] for i in range(0, len(hexstr), 128)]
    joined = "\n        + ".join(lines)
    return ("    internal static readonly byte[] %s =\n"
            "        Convert.FromHexString(\n%s);\n" % (cs_name, joined))


def emit_uint_array(cs_name, values):
    chunks, row = [], []
    for v in values:
        row.append("0x%08Xu" % (v & 0xFFFFFFFF))
        if len(row) == 8:
            chunks.append(", ".join(row))
            row = []
    if row:
        chunks.append(", ".join(row))
    body = ",\n            ".join(chunks)
    return ("    internal static readonly uint[] %s =\n        {\n"
            "            %s\n        };\n" % (cs_name, body))


HEADER = ("// <auto-generated>\n"
          "//   Generated by tools/airplay-port/extract_playfair_tables.py from the\n"
          "//   UxPlay reference sources (%s). Do not edit by hand.\n"
          "// </auto-generated>\n\n"
          "namespace CastReceiver.Core.AirPlay.FairPlay;\n\n")


def generate(paths, dst, names, class_name, summary, origin):
    decls = parse(paths)
    if not decls:
        raise SystemExit("no array declarations parsed from %s" % paths)
    parts, report, seen = [], [], set()
    for ctype, name, dims, values in decls:
        cs_name = names.get(name)
        if cs_name is None or not values:
            report.append("  skipped %s (%s)" % (name, dims))
            continue
        if cs_name in seen:
            report.append("  duplicate %s -> skipped" % name)
            continue
        seen.add(cs_name)
        cs_type = TYPE_MAP.get(ctype)
        if cs_type is None:
            raise SystemExit("unsupported C type %r for %s" % (ctype, name))
        parts.append(emit_byte_array(cs_name, values) if cs_type == "byte[]"
                     else emit_uint_array(cs_name, values))
        report.append("  %-20s -> %-18s %-8s count=%d %s"
                      % (name, cs_name, cs_type, len(values), dims))
    body = (HEADER % origin
            + "/// <summary>%s</summary>\n" % summary
            + "internal static class %s\n{\n" % class_name
            + "\n".join(parts) + "}\n")
    dst.parent.mkdir(parents=True, exist_ok=True)
    dst.write_text(body, encoding="utf-8")
    print("wrote %s (%d tables, %d bytes)" % (dst, len(parts), dst.stat().st_size))
    for line in report:
        print(line)


def main():
    if len(sys.argv) != 6:
        raise SystemExit(__doc__)
    generate([sys.argv[1], sys.argv[2]], Path(sys.argv[3]), TABLE_NAMES, "FairPlayTables",
             "FairPlay PlayFair 算法所需的全部常量表（由 UxPlay 参考实现自动生成）。",
             "lib/playfair/omg_hax.h + omg_hax.c")
    generate([sys.argv[4]], Path(sys.argv[5]), CONST_NAMES, "FairPlayConstants",
             "FairPlay fp-setup 握手用的固定应答（由 UxPlay 参考实现自动生成）。",
             "lib/fairplay_playfair.c")


if __name__ == "__main__":
    main()
